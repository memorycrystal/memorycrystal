/**
 * Build-identity stamp for the self-hosted Convex deploy (ILL-304).
 * The deploy script overwrites the committed placeholder, then restores it.
 */

export const PLACEHOLDER_MODULE = `/**
 * Committed placeholder. \`scripts/convex-deploy-self-hosted.mjs\` overwrites this
 * file before a deploy and restores these bytes afterwards, so the git tree
 * does not keep a generated SHA.
 */
export const BUILD_INFO = {
  commit: "unknown",
  dirty: false,
  builtAt: null as string | null,
  source: "unknown" as "unknown" | "generated",
};
`;

export function decideBuildInfo({ porcelain, allowDirty, commit, now }) {
  const dirty = String(porcelain ?? "").trim().length > 0;
  if (dirty && !allowDirty) {
    return {
      ok: false,
      code: 2,
      message: "refusing to deploy from a dirty tree; pass --allow-dirty to record dirty:true",
    };
  }
  return {
    ok: true,
    info: {
      commit: commit || "unknown",
      dirty,
      builtAt: new Date(now).toISOString(),
      source: "generated",
    },
  };
}

export function renderBuildInfoModule(info) {
  return `/**
 * Generated by scripts/convex-deploy-self-hosted.mjs. Restored after deploy.
 */
export const BUILD_INFO = {
  commit: ${JSON.stringify(info.commit)},
  dirty: ${info.dirty ? "true" : "false"},
  builtAt: ${JSON.stringify(info.builtAt)},
  source: "generated" as "unknown" | "generated",
};
`;
}
